replace_paragraph('@@P 题目要求在 6:00、12:00、18:00 三个时刻重新决策', '@@P 为考察各日内发布时点的价值，本文固定其余设置，只改变启用时点的组合，在正式评价期 334 天上回放。启用某时点意味着同时接入该时刻的官方光伏预报及对应融合结果、更新自建负荷预测的剩余段水平、使用该时点的储备统计并重新决策。因此，这项消融测量的是该时点预测更新与重新决策的综合价值，不能解释为官方光伏预报单独的经济价值，也不能解释为只增加一次求解的独立收益。结果见表 10，全部数据来自同一套代码的同一次批量实验，未重新调参。')
