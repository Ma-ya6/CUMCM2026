"""区分§5.3官方预报、自建预测和融合预测，并备份原文件。"""
from pathlib import Path
from datetime import datetime
import shutil

p = Path(__file__).resolve().parent.parent
backup = p / '_build/backups' / datetime.now().strftime('%Y%m%d_%H%M%S_prediction')
for name in ['论文3.docx', '论文3_LaTeX/论文3.tex', '论文3_LaTeX/论文3.pdf', '_build/src/03_问题三四检验评价.md']:
    dest = backup / name
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(p / name, dest)

f = p / '_build/src/03_问题三四检验评价.md'
s = f.read_text(encoding='utf8')
def replace_paragraph(start, new):
    global s
    lines = s.splitlines()
    indices = [i for i,v in enumerate(lines) if v.startswith(start)]
    assert len(indices) == 1, (start, indices)
    lines[indices[0]] = new
    s = '\n'.join(lines) + '\n'

replace_paragraph('@@P 问题三与问题二最根本的区别', r'''@@P 问题三在 0:00 制定首次计划，并在 6:00、12:00、18:00 更新输入、重新决策。须区分官方预报与自建模型预测：附件 3 提供每日 0:00、6:00、12:00、18:00 四个发布时刻的官方光伏预报，不提供负荷预报；本文自建预测模型则用此前日期的历史负荷与光伏实测数据生成当日负荷和光伏基础预测。问题三复用预测模型的结构，但采用自身的配置，不能把它与问题二视为完全相同的预测输入。

@@P 官方光伏预报的各列是发布时刻后相应小时的预测点。本文按十分钟物理段右端点作线性插值，发布时刻的起点锚值取当时已经可见的最近光伏实测值，并按此前历史确定的有效发电窗口处理夜间出力。记对齐后的官方预报为 $P^{off,(k)}_{d,i}$，自建日前光伏基础预测为 $P^{own}_{d,i}$。各发布时刻使用自己的官方版本，与同一自建基础预测按小时进行回归融合：$\widehat{P}^{(k)}_{d,i}=\max\{0,a_{d,k,h}P^{off,(k)}_{d,i}+b_{d,k,h}P^{own}_{d,i}+\delta_{d,k,h}\}$。回归系数只用第 $d$ 日之前的配对预报与实测样本估计；样本不足时退化为合并白天时段回归或等权平均。系数是含截距的回归系数，并非要求非负且和为 1 的组合权重；夜间再按历史有效发电窗口归零。决策层使用的是该融合光伏预测，而非直接使用官方原始预报。0:00 首次计划同样接入该时刻的官方预报。日内不重新训练自建光伏基础预测，变化来自官方发布版本及其对应的融合结果。

@@P 负荷预测完全来自本文模型。记日前基础预测为 $L^{own}_{d,i}$；在 $k>0$ 时，用截至发布时刻已执行段的实际负荷，对剩余段作阻尼水平修正：$\widehat{L}^{(k)}_{d,i}=\lambda^{(k)}_d L^{own}_{d,i}$，其中 $\lambda^{(k)}_d=\operatorname{clip}\{1+0.5[\sum_{i=1}^{6k}L_{d,i}/\max(\sum_{i=1}^{6k}L^{own}_{d,i},10^{-9})-1],0.85,1.15\}$，该修正只作用于尚未执行的时段；0:00 取 $\lambda^{(0)}_d=1$。这属于已观测负荷驱动的水平更新，不是官方负荷预报，也不是日内重新训练预测模型。因此，各发布时刻的净负荷输入由“日内修正的自建负荷预测减去融合光伏预测”构成。''')
replace_paragraph(r'@@P 式中 $\xi_{\ell,i}^{(k)}$', r'@@P 式中 $\xi_{\ell,i}^{(k)}=(L_{\ell,i}-P^{act}_{\ell,i})-(\widehat{L}^{(k)}_{\ell,i}-\widehat{P}^{(k)}_{\ell,i})$，即实际净负荷减去相应发布时刻的模型净负荷预测；其中负荷侧为自建预测及其日内水平修正，光伏侧为官方与自建预测的融合结果。储备并非只由官方光伏预报误差估计。四个物理残差窗口分别为 143、108、72、36 段，区别于 144、109、73、37 段的计划窗口。历史样本不足 20 天时储备取零，之后按式(24)取分位数，并沿用非负截断、4800 kWh 有效上限和充电能力爬坡规则。')
s = s.replace('其中的预测序列替换为该发布时刻的最新版本。', '其中负荷输入取该时刻的自建负荷预测及日内水平修正，光伏输入取该时刻官方预报与自建预测的融合结果。')
